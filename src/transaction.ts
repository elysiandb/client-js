import { checkNewId, entitySegment } from "./entity.js";
import { ElysianDBError } from "./errors.js";
import type { HttpClient, RequestOptions } from "./http.js";
import { segment } from "./http.js";
import type { CreateInput, Document, UpdateInput } from "./types.js";

export type TransactionState = "active" | "committed" | "rolled_back";

type CallOptions = Pick<RequestOptions, "signal" | "timeout" | "requestId" | "headers">;

/** Timeout of the rollback sent after a commit that got no answer. */
const ROLLBACK_TIMEOUT_MS = 10_000;

/** Operations of a transaction on one entity type, returned by `tx.entity<T>("name")`. */
export interface TransactionEntity<T extends { id: string }> {
    create(data: CreateInput<T>): Promise<T>;
    update(id: string, data: UpdateInput<T>): Promise<void>;
    delete(id: string): Promise<void>;
}

/**
 * A transaction: operations are queued on the server and applied atomically on `commit()`.
 * They cannot be read back before the commit, by this client or any other.
 *
 * Use `db.transaction(async (tx) => { ... })`, which commits or rolls back for you,
 * or `db.beginTransaction()` to drive it yourself.
 */
export class Transaction {
    private currentState: TransactionState = "active";

    constructor(private readonly http: HttpClient, readonly id: string) {}

    get state(): TransactionState {
        return this.currentState;
    }

    /**
     * Queues the creation of a document and returns it with its `id`. The ID is generated by the client
     * when missing, so that later operations of the transaction can reference the document.
     */
    async create<T extends { id: string } = Document>(entity: string, data: CreateInput<T>, call?: CallOptions): Promise<T> {
        this.ensureActive();
        const document = { ...data, id: data.id || randomId() } as unknown as T;
        checkNewId(document);
        await this.http.request("POST", `${this.path()}/entity/${entitySegment(entity)}`, { ...call, body: document });
        return document;
    }

    /** @deprecated Use `create()`. */
    write<T extends { id: string } = Document>(entity: string, data: CreateInput<T>): Promise<T> {
        return this.create<T>(entity, data);
    }

    /**
     * Queues a partial update. The document must already be stored: ElysianDB 0.2.3 rejects the update
     * of a document created in the same transaction (`400`). The commit fails if the document no longer
     * exists at that point.
     */
    async update<T extends { id: string } = Document>(
        entity: string,
        id: string,
        data: UpdateInput<T>,
        call?: CallOptions,
    ): Promise<void> {
        this.ensureActive();
        // Never retried: a retry after a lost answer would queue the operation twice.
        await this.http.request("PUT", this.documentPath(entity, id), { ...call, body: data, retries: 0 });
    }

    /** Queues the deletion of a document. */
    async delete(entity: string, id: string, call?: CallOptions): Promise<void> {
        this.ensureActive();
        await this.http.request("DELETE", this.documentPath(entity, id), { ...call, retries: 0 });
    }

    /** Operations on one entity type, typed with `T`. */
    entity<T extends { id: string } = Document>(name: string): TransactionEntity<T> {
        return {
            create: (data) => this.create<T>(name, data),
            update: (id, data) => this.update<T>(name, id, data),
            delete: (id) => this.delete(name, id),
        };
    }

    /**
     * Validates and applies every queued operation, or none of them: a schema error or an update
     * of a missing document rejects the whole commit.
     */
    async commit(call?: CallOptions): Promise<void> {
        this.ensureActive();
        try {
            await this.http.request("POST", `${this.path()}/commit`, { ...call, retries: 0 });
        } catch (error) {
            // Without an answer, the commit may not have reached ElysianDB, which never expires transactions.
            // Rolling back does nothing when the transaction was committed or discarded in the meantime.
            // It is not awaited: the server may be the reason why the commit got no answer.
            if (error instanceof ElysianDBError && error.code !== "HTTP_ERROR") {
                this.http
                    .request("POST", `${this.path()}/rollback`, {
                        headers: call?.headers,
                        requestId: call?.requestId,
                        timeout: ROLLBACK_TIMEOUT_MS,
                        retries: 0,
                    })
                    .catch(() => undefined);
            }
            throw error;
        } finally {
            // ElysianDB discards the transaction whether the commit succeeds or not.
            this.currentState = "committed";
        }
    }

    /** Discards every queued operation. Does nothing when the transaction is already finished. */
    async rollback(call?: CallOptions): Promise<void> {
        if (this.currentState !== "active") return;
        this.currentState = "rolled_back";
        await this.http.request("POST", `${this.path()}/rollback`, { ...call, retries: 0 });
    }

    private path(): string {
        return `/api/tx/${segment(this.id, "transaction ID")}`;
    }

    private documentPath(entity: string, id: string): string {
        return `${this.path()}/entity/${entitySegment(entity)}/${segment(id, "document ID")}`;
    }

    private ensureActive(): void {
        if (this.currentState !== "active") {
            throw new Error(`ElysianDB: transaction ${this.id} is already ${this.currentState.replace("_", " ")}`);
        }
    }
}

/** Alias kept for compatibility with 0.0.x. */
export type TransactionSession = Transaction;

function randomId(): string {
    const cryptoApi = (globalThis as {
        crypto?: { randomUUID?: () => string; getRandomValues?: <A extends Uint8Array>(array: A) => A };
    }).crypto;
    if (typeof cryptoApi?.randomUUID === "function") return cryptoApi.randomUUID();

    // Browsers only have `randomUUID()` on HTTPS pages, but `getRandomValues()` everywhere.
    const bytes = new Uint8Array(16);
    if (typeof cryptoApi?.getRandomValues === "function") {
        cryptoApi.getRandomValues(bytes);
    } else {
        for (let i = 0; i < bytes.length; i++) bytes[i] = (Math.random() * 256) | 0;
    }

    bytes[6] = (bytes[6] & 0x0f) | 0x40;
    bytes[8] = (bytes[8] & 0x3f) | 0x80;
    const hex = Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join("");
    return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}
